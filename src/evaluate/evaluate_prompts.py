def analyze_classification(data, output_dir, disc_0_label="Safety", disc_1_label="General Reasoning"):
    """
    Create the graphs analyzing the splits
    Inputs:
        data | str: The filename of the csv containing the classification data
        output_dir | str: The folder to save the graphs in
        disc_0_label | str: The label to associate with dimension 0
        disc_1_label | str: The label to associate with dimension 1
    Outputs:
        Graphs for each bin type for both classification and category
    """

    q = pd.read_csv(data)
    # Create the bins
    q['disc_0_bin'] = pd.qcut(q['Discrimination 0'], 100, labels=False)
    q['disc_1_bin'] = pd.qcut(q['Discrimination 1'], 100, labels=False)
    q['diff_0_bin'] = pd.qcut(q['Difficulty 0'], 100, labels=False)
    q['diff_1_bin'] = pd.qcut(q['Difficulty 1'], 100, labels=False)

    categorical_cols = ["disc_0_bin", "disc_1_bin", "diff_0_bin", "diff_1_bin", "benchmark"]

    result = {}

    # Create the safety classification label graphs
    for col in categorical_cols:
        percent = (
            q.groupby(col)["safe_label"]
            .value_counts(normalize=True)
            .unstack(fill_value=0)
            * 100
        )
        if col == "benchmark":
            percent = order_and_rename_benchmarks(percent)
        percent.to_csv(f"{output_dir}{col}.csv")
        graph_stacked_columns_classification(percent, col, output_dir, disc_0_label, disc_1_label)

    # Create the safety category label graphs
    for col in categorical_cols:
        percent = (
            q.groupby(col)["categories"]
            .value_counts(normalize=True)
            .unstack(fill_value=0)
            * 100
        )
        if col == "benchmark":
            percent = order_and_rename_benchmarks(percent)
        percent.to_csv(f"{output_dir}{col}_categories.csv")
        graph_stacked_columns_category(percent, col, output_dir, disc_0_label, disc_1_label)
